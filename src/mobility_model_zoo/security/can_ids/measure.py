"""Device evidence for picket-forest (feature 007, research R9, gate rule 15).

Three measurements of the whole detection chain (features, forest, alarm stage), each recorded
with its hardware and origin (constitution V):

- `host`: the host build of the C chain, timed over synthetic frames (origin `host`);
- `esp32-qemu`: the replay benchmark built for ESP32 and run in Espressif QEMU (origin
  `emulator`; memory is meaningful, latency is not representative);
- `esp8266`: the replay benchmark on a real ESP8266 board, for example the Wemos D1 mini (origin
  `real_board`, a named substitute for the reference board ESP32-S3).

The benchmark replays synthetic frames (no dataset frame is ever written into firmware) and checks
every score against the host build.
"""

from __future__ import annotations

import datetime as dt
import json
import re
import shutil
import socket
import subprocess
import time
from pathlib import Path

import numpy as np

from mobility_model_zoo.edge.paths import BUILD_DIR, REPO_ROOT
from mobility_model_zoo.security.can_ids import scorer
from mobility_model_zoo.security.can_ids.synth import generate

PIO_DIR = REPO_ROOT / "firmware" / "picket-forest" / "platformio"
SKETCH_SRC = REPO_ROOT / "firmware" / "picket-forest" / "esp8266" / "picket_forest_bench" / "src"
DETECTOR_OBJECTS = ("picket_forest.c.o", "msml_can_features.c.o", "msml_alarm.c.o")
DETECTOR_OBJECTS_V2 = ("picket_forest_v2.c.o", "msml_cal.c.o", "msml_alarm.c.o")


def _objects(export_dir: Path) -> tuple[str, ...]:
    return DETECTOR_OBJECTS_V2 if fmt_of(export_dir) == scorer.V2 else DETECTOR_OBJECTS


def fmt_of(export_dir: Path) -> str:
    """Output format of an export folder (0.2.0 exports carry a calibration table header)."""
    return scorer.V2 if (Path(export_dir) / "picket_forest_table.h").exists() else scorer.V1


SUBSTITUTE = "substitute for the reference board ESP32-S3"
RESULT = re.compile(r"PICKET_FOREST_RESULT (\{.*\})")


def test_vectors(export_dir: Path, n_frames: int = 4000, seed: int = 42) -> tuple[str, dict]:
    """C header with synthetic frames and the expected scores of the host build."""
    df = generate("fabrication", n_frames=n_frames, seed=seed)
    exe = scorer.build_scorer(export_dir, BUILD_DIR / "picket-forest" / "host", fmt=fmt_of(export_dir))
    scores, alarms = scorer.run_scorer(exe, df)
    ts_us = np.rint((df["ts"].to_numpy() - df["ts"].iloc[0]) * 1e6).astype(np.int64)
    rows = []
    for t, i, d, lab, data in zip(
        ts_us, df["can_id"], df["dlc"], df["label"], df[scorer.PAYLOAD].to_numpy(np.uint8), strict=True
    ):
        payload = ",".join(f"0x{b:02X}" for b in data)
        rows.append(f"    {{{int(t)}, 0x{int(i):03X}, {int(d)}, {int(lab)}, {{{payload}}}}},")
    lines = [
        "/* Generated by mobility_model_zoo.security.can_ids.measure. Synthetic frames",
        f" * (picket-synth fabrication, seed {seed}); expected scores from the host build. */",
        "#ifndef PICKET_FOREST_TEST_VECTORS_H",
        "#define PICKET_FOREST_TEST_VECTORS_H",
        "#include <stdint.h>",
        "#ifndef TV_STORAGE",
        "#define TV_STORAGE",
        "#endif",
        "typedef struct {",
        "    int64_t ts_us;",
        "    uint16_t can_id;",
        "    uint8_t dlc;",
        "    uint8_t label;",
        "    uint8_t data[8];",
        "} tv_frame_t;",
        f"#define TV_N_FRAMES {len(df)}",
        f"#define TV_EXPECTED_ALARMS {int(alarms.sum())}",
        "static const tv_frame_t tv_frames[TV_N_FRAMES] TV_STORAGE = {",
        *rows,
        "};",
        "static const float tv_expected_score[TV_N_FRAMES] TV_STORAGE = {",
        *(f"    {float(s)!r}f," for s in scores),
        "};",
        "#endif",
        "",
    ]
    meta = {"frames": len(df), "expected_alarms": int(alarms.sum()), "seed": seed}
    return "\n".join(lines), meta


def prepare_sketch(export_dir: Path, n_frames: int = 4000) -> dict:
    """Fill the sketch's generated src/: detector sources, exported headers, test vectors."""
    if SKETCH_SRC.exists():
        shutil.rmtree(SKETCH_SRC)
    SKETCH_SRC.mkdir(parents=True)
    srcs, headers, _, _ = scorer.layout(fmt_of(export_dir))
    for name, path in srcs.items():
        shutil.copy(path, SKETCH_SRC / name)
    for name in headers:
        shutil.copy(export_dir / name, SKETCH_SRC / name)
    header, meta = test_vectors(export_dir, n_frames=n_frames)
    (SKETCH_SRC / "test_vectors.h").write_text(header)
    return meta


def pio(*args: str) -> str:
    from mobility_model_zoo.edge.bench.flash import pio_cmd

    res = subprocess.run([*pio_cmd(), *args], capture_output=True, text=True)
    if res.returncode != 0:
        tail = "\n".join((res.stdout + res.stderr).strip().splitlines()[-30:])
        raise RuntimeError(f"PlatformIO {' '.join(args)} failed:\n{tail}")
    return res.stdout


def object_sizes(env: str, objects: tuple[str, ...] = DETECTOR_OBJECTS) -> dict[str, int]:
    """text/data/bss of the detector objects of a PlatformIO build (bytes)."""
    build = BUILD_DIR / "picket-forest" / "pio" / env
    tool = {
        "esp32": "xtensa-esp32-elf-size",
        "esp8266": "xtensa-lx106-elf-size",
        "mkrzero": "arm-none-eabi-size",
    }[env]
    exe = shutil.which(tool) or next(
        (str(p) for p in (Path.home() / ".platformio" / "packages").glob(f"toolchain-*/bin/{tool}")),
        None,
    )
    objs = [p for name in objects for p in build.rglob(name)]
    if exe is None or len(objs) < len(objects):
        raise RuntimeError(f"cannot size the detector objects of {env} ({tool}, {len(objs)} objects)")
    out = subprocess.run([exe, "-t", *map(str, objs)], capture_output=True, text=True, check=True).stdout
    total = out.strip().splitlines()[-1].split()
    return {"text": int(total[0]), "data": int(total[1]), "bss": int(total[2])}


def _read_result(read_line, timeout: float) -> dict:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        line = read_line()
        m = RESULT.search(line or "")
        if m:
            return json.loads(m.group(1))
    raise TimeoutError("no PICKET_FOREST_RESULT line")


def run_qemu(export_dir: Path, port: int = 5565, timeout: float = 180.0) -> dict:
    from mobility_model_zoo.edge.bench import qemu

    meta = prepare_sketch(export_dir)
    pio("run", "-d", str(PIO_DIR), "-e", "esp32")
    build = BUILD_DIR / "picket-forest" / "pio" / "esp32"
    hm = json.loads((build / "hil_manifest.json").read_text())
    fw = BUILD_DIR / "picket-forest" / "fw-esp32"
    fw.mkdir(parents=True, exist_ok=True)
    images = []
    for img in hm["flash_images"]:
        src = Path(img["path"])
        shutil.copy(src, fw / src.name)
        images.append({"offset": img["offset"], "file": src.name})
    manifest = {
        "mcu": hm.get("mcu") or "esp32",
        "flash_size": hm.get("flash_size") or "4MB",
        "flash_images": images,
    }
    (fw / "manifest.json").write_text(json.dumps(manifest))
    qemu.start(fw, port)
    try:
        sock = socket.create_connection(("127.0.0.1", port), timeout=5)
        buf = sock.makefile("r", errors="replace")
        sock.settimeout(timeout)
        result = _read_result(buf.readline, timeout)
    finally:
        qemu.stop(port)
    return {"result": result, "sizes": object_sizes("esp32", _objects(export_dir)), "vectors": meta}


def run_board(export_dir: Path, board_id: str, timeout: float = 120.0, env: str = "esp8266") -> dict:
    import serial

    from mobility_model_zoo.edge.bench.config import load_lab
    from mobility_model_zoo.edge.bench.discovery import resolve_port

    board = load_lab().board(board_id)
    port = resolve_port(board)
    meta = prepare_sketch(export_dir)
    pio("run", "-d", str(PIO_DIR), "-e", env, "-t", "upload", "--upload-port", port)
    with serial.Serial(port, 115200, timeout=2) as ser:
        result = _read_result(lambda: ser.readline().decode(errors="replace"), timeout)
    return {
        "result": result,
        "sizes": object_sizes(env, _objects(export_dir)),
        "vectors": meta,
        "board": board_id,
    }


MKRZERO_FRAMES = 2000  # SAMD21 has 32 KB RAM: the timing buffer holds one uint32 per frame


def run_mkrzero(export_dir: Path, board_id: str, timeout: float = 180.0) -> dict:
    """Arduino MKR Zero (SAMD21 Cortex-M0+, 48 MHz, no FPU): flash with bossac, read over USB."""
    import serial

    from mobility_model_zoo.edge.bench.config import load_lab
    from mobility_model_zoo.edge.bench.discovery import resolve_port

    board = load_lab().board(board_id)
    port = resolve_port(board)
    meta = prepare_sketch(export_dir, n_frames=MKRZERO_FRAMES)
    pio("run", "-d", str(PIO_DIR), "-e", "mkrzero", "-t", "upload", "--upload-port", port)
    time.sleep(3)  # the board re-enumerates after the bootloader
    port = resolve_port(board)
    with serial.Serial(port, 115200, timeout=2) as ser:
        result = _read_result(lambda: ser.readline().decode(errors="replace"), timeout)
    return {
        "result": result,
        "sizes": object_sizes("mkrzero", _objects(export_dir)),
        "vectors": meta,
        "board": board_id,
    }


def run_host(export_dir: Path, n_frames: int = 200_000) -> dict:
    df = generate("fabrication", n_frames=n_frames, seed=7)
    exe = scorer.build_scorer(export_dir, BUILD_DIR / "picket-forest" / "host", fmt=fmt_of(export_dir))
    t0 = time.perf_counter()
    scorer.run_scorer(exe, df)
    us = (time.perf_counter() - t0) / n_frames * 1e6
    import platform

    return {
        "latency_us": us,
        "frames": n_frames,
        "hardware": f"host {platform.machine()} ({platform.system()})",
    }


def _metric(name, value, unit, desc, hardware, origin, n=None) -> dict:
    return {
        "name": name,
        "value": round(float(value), 3),
        "unit": unit,
        "description": desc,
        "reference": None,
        "benchmark": None,
        "n_items": n,
        "hardware": hardware,
        "origin": origin,
        "date": dt.date.today().isoformat(),
    }


def metrics(target: str, run: dict) -> list[dict]:
    """Results-format metrics of one measurement; refuses runs with score mismatches."""
    if target == "host":
        return [
            _metric(
                "latency_us_host",
                run["latency_us"],
                "us",
                "whole chain per frame, host build incl. file I/O",
                run["hardware"],
                "host",
                run["frames"],
            )
        ]
    r, sizes = run["result"], run["sizes"]
    if r.get("score_mismatches", 1) != 0:
        raise ValueError(
            f"{target}: {r.get('score_mismatches')} score mismatches against the host build"
        )
    lat = r["latency_us"]
    if target == "esp32-qemu":
        hw, origin, sfx = (
            f"ESP32 in Espressif QEMU, {r['cpu_mhz']} MHz nominal",
            "emulator",
            "_esp32_qemu",
        )
        note = " (emulator: not representative)"
    elif target == "esp32":
        hw = f"ESP32 (board {run.get('board')}), {r['cpu_mhz']} MHz, single-precision FPU"
        origin, sfx, note = "real_board", "_esp32", ""
    elif target == "mkrzero":
        hw = f"SAMD21 Cortex-M0+ (board {run.get('board')}), {r['cpu_mhz']} MHz, no FPU"
        origin, sfx, note = "real_board", "_samd21", ""
    else:
        board = run.get("board") or "esp8266"
        hw = f"ESP8266 (board {board}), {r['cpu_mhz']} MHz, {SUBSTITUTE}"
        origin, sfx, note = "real_board", "", ""
    out = [
        _metric(
            f"latency_us{sfx}",
            lat["median"],
            "us",
            f"whole chain per frame, median{note}",
            hw,
            origin,
            r["frames"],
        ),
        _metric(
            f"latency_p99_us{sfx}",
            lat["p99"],
            "us",
            f"whole chain per frame, 99th percentile{note}",
            hw,
            origin,
            r["frames"],
        ),
        _metric(
            f"flash_kb{sfx}",
            (sizes["text"] + sizes["data"]) / 1024,
            "KiB",
            "detector code and constants (features, forest, alarm stage), from the object files",
            hw,
            origin,
        ),
        _metric(
            f"ram_kb{sfx}",
            (sizes["data"] + sizes["bss"] + r["state_bytes"]) / 1024,
            "KiB",
            "detector static data plus the detector state",
            hw,
            origin,
        ),
    ]
    if target == "esp32-qemu":
        # rule 15 reads the plain names; for experimental releases the emulator may provide them
        # (origin says so); a later real-board run replaces them
        out += [{**m, "name": m["name"].replace("_esp32_qemu", "")} for m in out]
    return out


def merge(path: Path, new: list[dict], model: str, version: str) -> dict:
    """Merge metrics into a performance results file (replacing metrics of the same name)."""
    data = (
        json.loads(path.read_text())
        if path.exists()
        else {
            "kind": "performance",
            "model": model,
            "version": version,
            "synthetic": False,
            "source_run": "security can-ids measure",
            "metrics": [],
        }
    )
    names = {m["name"] for m in new}
    data["metrics"] = [m for m in data["metrics"] if m["name"] not in names] + new
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=1) + "\n")
    return data
