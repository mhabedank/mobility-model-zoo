"""Release export of picket-forest 0.2.0 (feature 010).

The release model is the harness's `picket-forest-v2` trained on the training captures of all four
can-train-and-test sets of `can-ids-v3`, frame threshold chosen on their validation captures. The
export writes every staged file:

    picket_forest_model.h        emlearn forest (float32 split literals, bit-exact with scikit-learn)
    picket_forest_config.h       threshold, event decision, alarm stage
    picket_forest_table.h        calibration table; the staged one belongs to the synthetic example
                                 vehicle, users generate their own with `table_header`
    model.joblib                 host reference (scikit-learn forest and parameters)
    config.json                  recipe, benchmark hash, parity
    c/*.c, c/*.h                 detector, calibrated features, alarm stage
    sbom.cdx.json                CycloneDX bill of materials of the device code

and checks C against Python on ROAD captures (scores bit-exact, alarms identical).
"""

from __future__ import annotations

import hashlib
import json
import platform
import shutil
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from mobility_model_zoo.security.can_ids import calibrated as cal
from mobility_model_zoo.security.can_ids import forest, scorer
from mobility_model_zoo.security.can_ids.evaluate import DEFAULT_ALARM, code_commit
from mobility_model_zoo.security.can_ids.forest_features import alarms, to_microseconds

EXAMPLE_SEED = 42
EXAMPLE_ATTACKS = ("fabrication", "dos", "fuzzing")


def _f32(v: float) -> str:
    return forest.float32_split_literal(float(np.float32(v)))


def model_header(clf, path: Path) -> None:
    emlearn = forest._import_emlearn()
    original = emlearn.cgen.constant

    def exact_constant(val, dtype="float"):
        return forest.float32_split_literal(float(val)) if dtype == "float" else original(val, dtype)

    emlearn.cgen.constant = exact_constant
    state = np.geterr()
    try:
        cmodel = emlearn.convert(clf, method="inline", dtype="float")
        cmodel.save(file=str(path), name=forest.MODEL_NAME)
    finally:
        emlearn.cgen.constant = original
        np.seterr(**state)


def config_header(
    path: Path, threshold: float, alarm: dict, rules_margin: float = cal.RULES_MARGIN
) -> None:
    lines = [
        "/* Generated by mobility_model_zoo.security.can_ids.release_export_v2. */",
        "#ifndef PICKET_FOREST_CONFIG_H",
        "#define PICKET_FOREST_CONFIG_H",
        "#define PICKET_FOREST_FORMAT 2",
        f"#define PICKET_FOREST_THRESHOLD ({_f32(threshold)})",
        f"#define PICKET_FOREST_RULES_MARGIN ({float(rules_margin)!r})",
        f"#define PICKET_FOREST_ALARM_K {int(alarm['k'])}",
        f"#define PICKET_FOREST_ALARM_WINDOW_US {int(alarm['window_ms']) * 1000}",
        f"#define PICKET_FOREST_ALARM_HOLDOFF_US {int(alarm['holdoff_ms']) * 1000}",
        "#endif",
        "",
    ]
    path.write_text("\n".join(lines))


def table_header(table: cal.Table, path: Path, note: str) -> None:
    """C header with the calibration table of one vehicle (sorted by CAN ID)."""
    e = table.entries()
    rows = [
        f"    {{0x{int(r['id']):03X}u, {int(r['period_us'])}u, {int(r['window_us'])}u, "
        f"{int(r['max_count'])}u, {int(r['dlc'])}u}},"
        for r in e
    ]
    lines = [
        "/* Generated by mobility_model_zoo.security.can_ids.release_export_v2.",
        f" * Calibration table: {note}",
        f" * {len(e)} IDs, {table.seconds / 60:.1f} min of benign traffic. Replace it with the table of",
        " * your vehicle (`zoo-security can-ids v2 table`). */",
        "#ifndef PICKET_FOREST_TABLE_H",
        "#define PICKET_FOREST_TABLE_H",
        '#include "msml_cal.h"',
        f"#define PICKET_FOREST_TABLE_N {len(e)}",
        f"#define PICKET_FOREST_BUS_RATE ({_f32(table.bus_rate)})",
        f"static const msml_cal_entry_t picket_forest_table_entries[{max(len(e), 1)}] = {{",
        *rows,
        "};",
        "#endif",
        "",
    ]
    path.write_text("\n".join(lines))


def reference(cap: dict, table: cal.Table, clf, threshold: float, alarm: dict = DEFAULT_ALARM):
    """Python reference of the whole chain: (float32 forest scores, uint8 alarms). The rules on the
    calibrated features decide; the forest score is information."""
    x = cal.features(cap, table)
    s = forest.vote_score(clf, x).astype(np.float32)
    flags = cal.rules(x) > 0
    a = alarms(to_microseconds(cap["ts"]), flags, alarm["k"], alarm["window_ms"], alarm["holdoff_ms"])
    return s, np.asarray(a, dtype=np.uint8)


def _frames(cap: dict) -> pd.DataFrame:
    df = pd.DataFrame({"ts": cap["ts"], "can_id": cap["can_id"].astype(np.uint16), "dlc": cap["dlc"]})
    for i in range(8):
        df[f"b{i}"] = cap["data"][:, i]
    return df


def build(headers_dir: Path, out: Path, sources_dir: Path | None = None) -> Path:
    return scorer.build_scorer(headers_dir, out, sources_dir=sources_dir, fmt=scorer.V2)


def parity(clf, threshold: float, caps: list[dict], table: cal.Table, work: Path) -> dict[str, int]:
    """C chain (built with this table) against the Python reference on real captures."""
    work.mkdir(parents=True, exist_ok=True)
    hdr = work / "headers"
    hdr.mkdir(exist_ok=True)
    model_header(clf, hdr / "picket_forest_model.h")
    config_header(hdr / "picket_forest_config.h", threshold, DEFAULT_ALARM)
    table_header(table, hdr / "picket_forest_table.h", "parity check")
    exe = build(hdr, work / "build")
    frames = score_mismatch = alarm_mismatch = 0
    for c in caps:
        s_py, a_py = reference(c, table, clf, threshold)
        s_c, a_c = scorer.run_scorer(exe, _frames(c))
        frames += len(s_py)
        score_mismatch += int(np.count_nonzero(s_c.view(np.uint32) != s_py.view(np.uint32)))
        alarm_mismatch += int(np.count_nonzero(a_c != a_py))
    return {"frames": frames, "score_mismatches": score_mismatch, "alarm_mismatches": alarm_mismatch}


def example_table() -> cal.Table:
    from mobility_model_zoo.security.can_ids.detectors import make_capture
    from mobility_model_zoo.security.can_ids.synth import generate

    c = make_capture(generate("fabrication", n_frames=40000, seed=EXAMPLE_SEED), "synthetic", "benign")
    keep = c["y"] == 0
    benign = {
        k: (v[keep] if isinstance(v, np.ndarray) and v.shape[:1] == keep.shape else v)
        for k, v in c.items()
    }
    return cal.calibrate([benign])


def sbom(out_dir: Path) -> dict:
    from mobility_model_zoo.security.can_ids.release_export import sbom as sbom_v1

    return sbom_v1(out_dir)


def export(
    out_dir: Path,
    manifest: dict,
    sources: dict,
    cache: Path | None,
    parity_caps: list[dict],
    parity_table: cal.Table,
) -> dict[str, Any]:
    import joblib

    from mobility_model_zoo.security.can_ids import evaluate_v2 as ev2

    tabs = ev2.tables(manifest, sources, cache)
    det, calib = ev2.release_model("picket-forest-v2", manifest, sources, cache, tabs)
    clf, thr = det.model, det.info["frame_threshold"]
    if out_dir.exists():
        shutil.rmtree(out_dir)
    (out_dir / "c").mkdir(parents=True)
    model_header(clf, out_dir / "picket_forest_model.h")
    config_header(out_dir / "picket_forest_config.h", thr, DEFAULT_ALARM)
    table_header(
        example_table(),
        out_dir / "picket_forest_table.h",
        "synthetic example vehicle (picket-synth, seed 42)",
    )
    srcs, _, _, _ = scorer.layout(scorer.V2)
    for name, path in srcs.items():
        shutil.copy(path, out_dir / "c" / name)
    joblib.dump(
        {
            "model": clf,
            "threshold": thr,
            "decision": "rules",
            "rules_margin": cal.RULES_MARGIN,
            "alarm": DEFAULT_ALARM,
            "features": cal.FEATURE_NAMES,
            "format": scorer.V2,
        },
        out_dir / "model.joblib",
    )
    par = parity(clf, thr, parity_caps, parity_table, out_dir.parent / "export-v2-parity")
    if par["score_mismatches"] or par["alarm_mismatches"]:
        raise SystemExit(f"C and Python differ: {par}")
    config = {
        "model": "picket-forest",
        "version": "0.2.0",
        "format": scorer.V2,
        "algorithm": (
            "calibrated features (msml_cal); rules decide; forest score (emlearn C) as information"
        ),
        "hyperparameters": {**det.info["hyperparameters"], "min_samples_leaf": 20},
        "tree_nodes": det.info["tree_nodes"],
        "inputs": cal.FEATURE_NAMES,
        "frame_threshold": thr,
        "decision": {"by": "rules on the calibrated features", "rules_margin": cal.RULES_MARGIN},
        "alarm": DEFAULT_ALARM,
        "training": (
            "train_01 of set_01..set_04 of can-train-and-test (can-ids-v3); validation captures select"
        ),
        "benchmark": manifest["benchmark"],
        "manifest_sha256": hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest(),
        "code_commit": code_commit(),
        "parity_c_vs_python": {**par, "host": platform.machine(), "captures": "ROAD test captures"},
    }
    (out_dir / "config.json").write_text(json.dumps(config, indent=1, default=float) + "\n")
    (out_dir / "sbom.cdx.json").write_text(json.dumps(sbom(out_dir), indent=1) + "\n")
    return config


def write_examples(export_dir: Path, out_dir: Path) -> list[Path]:
    """Three synthetic examples (fabrication, DoS, fuzzing) of the example vehicle, expected scores
    and alarms from the staged C chain."""
    from mobility_model_zoo.security.can_ids.synth import generate

    exe = build(export_dir, export_dir.parent / "examples-v2-build", sources_dir=export_dir / "c")
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.json"):
        old.unlink()
    written = []
    for i, attack in enumerate(EXAMPLE_ATTACKS):
        gen = {"name": "picket-synth", "version": 1, "seed": EXAMPLE_SEED, "attack": attack}
        df = generate(attack, n_frames=3000, seed=EXAMPLE_SEED)
        ex = scorer.example_from_frames(df, exe, "synthetic", gen)
        path = out_dir / f"0{i + 1}-{attack}.json"
        path.write_text(json.dumps(ex) + "\n", encoding="utf-8")
        written.append(path)
    return written
